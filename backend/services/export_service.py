"""
StudyMind AI - Export Service
Generates PDF, DOCX, and TXT exports.
"""

import io
import os
import json
import logging
from typing import Dict, Any, Optional

logger = logging.getLogger(__name__)


class ExportService:
    """Export content to PDF, DOCX, and TXT formats."""

    def export_pdf(self, content: Any, title: str = "StudyMind Export") -> bytes:
        """Generate a PDF document."""
        try:
            from reportlab.lib import colors
            from reportlab.lib.pagesizes import A4
            from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
            from reportlab.lib.units import inch
            from reportlab.platypus import (
                SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak
            )
        except ImportError:
            raise ImportError("reportlab is required for PDF export.")

        buffer = io.BytesIO()
        doc = SimpleDocTemplate(buffer, pagesize=A4, topMargin=0.75 * inch, bottomMargin=0.75 * inch)
        styles = getSampleStyleSheet()

        # Custom styles
        title_style = ParagraphStyle(
            'CustomTitle', parent=styles['Title'], fontSize=20, spaceAfter=20,
            textColor=colors.HexColor('#1E293B')
        )
        heading_style = ParagraphStyle(
            'CustomHeading', parent=styles['Heading2'], fontSize=14, spaceAfter=10,
            textColor=colors.HexColor('#7C3AED'), spaceBefore=15
        )
        body_style = ParagraphStyle(
            'CustomBody', parent=styles['Normal'], fontSize=11, leading=16,
            spaceAfter=8
        )
        badge_style = ParagraphStyle(
            'Badge', parent=styles['Normal'], fontSize=9, textColor=colors.HexColor('#6366F1')
        )

        elements = []
        elements.append(Paragraph(title, title_style))
        elements.append(Paragraph("Generated by StudyMind AI", badge_style))
        elements.append(Spacer(1, 20))

        # Handle different content types
        if isinstance(content, dict):
            if "topics" in content:
                # Consolidated question document
                stats = content.get("stats", {})
                elements.append(Paragraph(f"Total Questions: {stats.get('total_questions', 0)} | "
                                         f"Unique: {stats.get('unique_questions', 0)} | "
                                         f"Duplicates: {stats.get('duplicate_questions', 0)}", body_style))
                elements.append(Spacer(1, 15))

                for topic in content.get("topics", []):
                    elements.append(Paragraph(topic["name"], heading_style))
                    for q in topic.get("questions", []):
                        freq_text = f" [{q.get('frequency_label', '')} - appeared {q.get('frequency', 1)} times]"
                        elements.append(Paragraph(
                            f"Q{q['number']}. {self._escape_xml(q['question'])}{freq_text}",
                            body_style
                        ))
                        if q.get("years"):
                            elements.append(Paragraph(
                                f"   Years: {', '.join(q['years'])}",
                                badge_style
                            ))
                        elements.append(Spacer(1, 5))

            elif "content" in content:
                self._add_content_to_pdf(elements, content["content"], body_style, heading_style)
            elif "error" in content:
                elements.append(Paragraph(f"Error: {content['error']}", body_style))
        elif isinstance(content, list):
            for item in content:
                if isinstance(item, dict):
                    q = item.get("question", "")
                    a = item.get("answer", item.get("correct_answer", ""))
                    elements.append(Paragraph(f"Q: {self._escape_xml(q)}", heading_style))
                    elements.append(Paragraph(f"A: {self._escape_xml(str(a))}", body_style))
                    if "explanation" in item:
                        elements.append(Paragraph(f"Explanation: {self._escape_xml(item['explanation'])}", badge_style))
                    elements.append(Spacer(1, 10))
                else:
                    elements.append(Paragraph(self._escape_xml(str(item)), body_style))
        elif isinstance(content, str):
            for para in content.split('\n'):
                if para.strip():
                    if para.startswith('#'):
                        text = para.lstrip('#').strip()
                        elements.append(Paragraph(self._escape_xml(text), heading_style))
                    else:
                        elements.append(Paragraph(self._escape_xml(para), body_style))

        if not elements or len(elements) <= 3:
            elements.append(Paragraph("No content to export.", body_style))

        doc.build(elements)
        return buffer.getvalue()

    def _add_content_to_pdf(self, elements, content, body_style, heading_style):
        from reportlab.platypus import Paragraph

        if isinstance(content, str):
            for line in content.split('\n'):
                if line.strip():
                    elements.append(Paragraph(self._escape_xml(line), body_style))
        elif isinstance(content, list):
            for item in content:
                if isinstance(item, dict):
                    for key, val in item.items():
                        elements.append(Paragraph(f"{key}: {self._escape_xml(str(val))}", body_style))
                else:
                    elements.append(Paragraph(self._escape_xml(str(item)), body_style))

    def export_docx(self, content: Any, title: str = "StudyMind Export") -> bytes:
        """Generate a DOCX document."""
        try:
            from docx import Document
            from docx.shared import Pt, RGBColor, Inches
            from docx.enum.text import WD_ALIGN_PARAGRAPH
        except ImportError:
            raise ImportError("python-docx is required for DOCX export.")

        doc = Document()

        # Title
        title_para = doc.add_heading(title, level=0)
        subtitle = doc.add_paragraph("Generated by StudyMind AI")
        subtitle.runs[0].font.color.rgb = RGBColor(0x6B, 0x72, 0x80)
        doc.add_paragraph("")

        if isinstance(content, dict):
            if "topics" in content:
                stats = content.get("stats", {})
                doc.add_paragraph(
                    f"Total: {stats.get('total_questions', 0)} | "
                    f"Unique: {stats.get('unique_questions', 0)} | "
                    f"Duplicates: {stats.get('duplicate_questions', 0)}"
                )
                for topic in content.get("topics", []):
                    doc.add_heading(topic["name"], level=1)
                    for q in topic.get("questions", []):
                        p = doc.add_paragraph()
                        run = p.add_run(f"Q{q['number']}. {q['question']}")
                        run.bold = True
                        freq_p = doc.add_paragraph(
                            f"   Frequency: {q.get('frequency', 1)} | {q.get('frequency_label', 'Normal')}"
                        )
                        freq_p.runs[0].font.color.rgb = RGBColor(0x7C, 0x3A, 0xED)
                        if q.get("years"):
                            doc.add_paragraph(f"   Years: {', '.join(q['years'])}")
            elif "content" in content:
                self._add_content_to_docx(doc, content["content"])
        elif isinstance(content, list):
            for item in content:
                if isinstance(item, dict):
                    p = doc.add_paragraph()
                    p.add_run(f"Q: {item.get('question', '')}").bold = True
                    doc.add_paragraph(f"A: {item.get('answer', item.get('correct_answer', ''))}")
                    if "explanation" in item:
                        exp = doc.add_paragraph(f"Explanation: {item['explanation']}")
                        exp.runs[0].font.color.rgb = RGBColor(0x6B, 0x72, 0x80)
                    doc.add_paragraph("")
                else:
                    doc.add_paragraph(str(item))
        elif isinstance(content, str):
            for para in content.split('\n'):
                if para.strip():
                    if para.startswith('# '):
                        doc.add_heading(para[2:], level=1)
                    elif para.startswith('## '):
                        doc.add_heading(para[3:], level=2)
                    elif para.startswith('### '):
                        doc.add_heading(para[4:], level=3)
                    else:
                        doc.add_paragraph(para)

        buffer = io.BytesIO()
        doc.save(buffer)
        return buffer.getvalue()

    def _add_content_to_docx(self, doc, content):
        if isinstance(content, str):
            for line in content.split('\n'):
                if line.strip():
                    doc.add_paragraph(line)
        elif isinstance(content, list):
            for item in content:
                if isinstance(item, dict):
                    for k, v in item.items():
                        doc.add_paragraph(f"{k}: {v}")
                else:
                    doc.add_paragraph(str(item))

    def export_txt(self, content: Any, title: str = "StudyMind Export") -> bytes:
        """Generate a plain text document."""
        lines = [title, "=" * len(title), f"Generated by StudyMind AI", "", ""]

        if isinstance(content, dict):
            if "topics" in content:
                stats = content.get("stats", {})
                lines.append(f"Total Questions: {stats.get('total_questions', 0)}")
                lines.append(f"Unique Questions: {stats.get('unique_questions', 0)}")
                lines.append(f"Duplicate Questions: {stats.get('duplicate_questions', 0)}")
                lines.append("")

                for topic in content.get("topics", []):
                    lines.append(f"\n{'='*50}")
                    lines.append(f"TOPIC: {topic['name']}")
                    lines.append(f"{'='*50}\n")

                    for q in topic.get("questions", []):
                        lines.append(f"Q{q['number']}. {q['question']}")
                        lines.append(f"   Frequency: {q.get('frequency', 1)} ({q.get('frequency_label', 'Normal')})")
                        if q.get("years"):
                            lines.append(f"   Years: {', '.join(q['years'])}")
                        lines.append("")

            elif "content" in content:
                c = content["content"]
                if isinstance(c, str):
                    lines.append(c)
                elif isinstance(c, list):
                    for item in c:
                        if isinstance(item, dict):
                            lines.append(json.dumps(item, indent=2))
                        else:
                            lines.append(str(item))
                        lines.append("")
        elif isinstance(content, list):
            for item in content:
                if isinstance(item, dict):
                    lines.append(f"Q: {item.get('question', '')}")
                    lines.append(f"A: {item.get('answer', item.get('correct_answer', ''))}")
                    if "explanation" in item:
                        lines.append(f"Explanation: {item['explanation']}")
                    lines.append("")
                else:
                    lines.append(str(item))
        elif isinstance(content, str):
            lines.append(content)

        return "\n".join(lines).encode("utf-8")

    def _escape_xml(self, text: str) -> str:
        """Escape XML special characters for ReportLab."""
        text = str(text)
        text = text.replace("&", "&amp;")
        text = text.replace("<", "&lt;")
        text = text.replace(">", "&gt;")
        return text
